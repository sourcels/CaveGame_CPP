GameMap::GameMap(const std::vector<std::string>& customMap) {
    map = customMap;
}

int GameMap::mapWidth()  const { return (int)map[0].size(); }
int GameMap::mapHeight() const { return (int)map.size(); }

std::pair<int,int> GameMap::findSymbol(char symbol) const {
    for (int y = 0; y < (int)map.size(); y++)
        for (int x = 0; x < (int)map[y].size(); x++)
            if (map[y][x] == symbol) return {x, y};
    return {-1, -1};
}

void GameMap::eraseSymbol(int x, int y) {
    map[y][x] = ' ';
}

char GameMap::getCharOfMap(int y, int x) const {
    return map[y][x];
}
